-- =============================================================================
-- Green Economy Monitoring System – مخطط قاعدة البيانات (SQLite)
-- =============================================================================
-- ملاحظة: هذا الملف للتوثيق والمرجع فقط.
--          يتم إنشاء قاعدة البيانات تلقائياً عند تشغيل app.py
--          ملف قاعدة البيانات: database/green_economy.db
-- =============================================================================


-- =============================================================================
-- جدول المستخدمين (users)
-- يحفظ بيانات كل من يستطيع تسجيل الدخول للنظام
-- =============================================================================
CREATE TABLE IF NOT EXISTS users (
    id            INTEGER PRIMARY KEY AUTOINCREMENT, -- رقم تعريفي فريد يزيد تلقائياً
    username      TEXT    NOT NULL UNIQUE,           -- اسم المستخدم (لا يتكرر)
    password_hash TEXT    NOT NULL,                  -- كلمة المرور مشفّرة (لا تُحفظ نصاً)
    role          TEXT    NOT NULL DEFAULT 'viewer', -- الدور: admin  أو  user  أو  viewer
    created_at    TEXT    DEFAULT (datetime('now'))  -- تاريخ ووقت إنشاء الحساب
);


-- =============================================================================
-- جدول المؤسسات (institutions)
-- يحفظ قراءات المؤشرات البيئية لكل مؤسسة في كل سنة
-- =============================================================================
CREATE TABLE IF NOT EXISTS institutions (
    id                          INTEGER PRIMARY KEY AUTOINCREMENT, -- رقم تعريفي فريد
    name                        TEXT    NOT NULL,                  -- اسم المؤسسة
    year                        INTEGER NOT NULL,                  -- السنة التي تخص هذه القراءة
    energy_consumption          REAL    NOT NULL,                  -- استهلاك الطاقة (ميغاواط ساعة)
    renewable_energy_percentage REAL    NOT NULL,                  -- نسبة الطاقة المتجددة (0–100 %)
    carbon_emissions            REAL    NOT NULL,                  -- انبعاثات الكربون (طن)
    green_projects              INTEGER NOT NULL DEFAULT 0,        -- عدد المشاريع الخضراء المنفّذة
    water_usage                 REAL    NOT NULL DEFAULT 0,        -- استهلاك المياه (متر مكعب)
    waste_recycling_percentage  REAL    NOT NULL DEFAULT 0,        -- نسبة إعادة تدوير النفايات (0–100 %)
    created_at  TEXT DEFAULT (datetime('now')),                    -- تاريخ إضافة السجل
    updated_at  TEXT DEFAULT (datetime('now'))                     -- تاريخ آخر تعديل على السجل
);
-- القيد المنطقي: المؤسسة + السنة يجب أن يكونا فريدَين معاً
-- (يُطبَّق في الكود عبر التحقق من التكرار قبل الإدراج)


-- =============================================================================
-- جدول الإعدادات (settings)
-- يحفظ إعدادات النظام كأزواج مفتاح–قيمة
-- =============================================================================
CREATE TABLE IF NOT EXISTS settings (
    key   TEXT PRIMARY KEY, -- اسم الإعداد (مثال: carbon_threshold)
    value TEXT NOT NULL DEFAULT '' -- قيمة الإعداد
);
-- أمثلة على إعدادات محفوظة:
--   carbon_threshold  →  الحد الأقصى لانبعاثات الكربون قبل إرسال تنبيه


-- =============================================================================
-- جدول سجل التدقيق (audit_log)
-- يسجّل كل عملية مهمة (إضافة / تعديل / حذف) مع اسم المستخدم والوقت
-- =============================================================================
CREATE TABLE IF NOT EXISTS audit_log (
    id         INTEGER PRIMARY KEY AUTOINCREMENT, -- رقم تعريفي فريد
    username   TEXT    NOT NULL,                  -- اسم المستخدم الذي نفّذ العملية
    action     TEXT    NOT NULL,                  -- وصف العملية (مثال: إضافة مؤسسة)
    details    TEXT    DEFAULT '',                -- تفاصيل إضافية (اسم المؤسسة، ID، ...)
    created_at TEXT    DEFAULT (datetime('now'))  -- تاريخ ووقت تنفيذ العملية
);


